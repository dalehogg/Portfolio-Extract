      <article data-reveal>
        <h3>How would you describe your work?</h3>
        <p>Visual Narrative: I am interested in exploring the mythology of historical archetype, and it’s cross cultural and contemporary significance. I enjoy the creative challenge of the storytelling and problem solving process.</p>
      </article>
      <article data-reveal>
        <h3>When inspiration hits how do you channel that into your work, what’s the process?</h3>
        <p>I use visual research to compose a collage of images to create the narrative I seek. Then I choose the medium in which best will serve the purpose, it is usually a combination of 2D and 3D and can be seen in my mind’s eye as completed. I draw this out before beginning the making</p>
      </article>
      <article data-reveal>
        <h3>What inspires you generally?</h3>
        <p>A real connection to Papatuanku (mother earth), the indigenous world view. Te Ao Maaori, Early mythology and psychology. Researching the divine elements and the significance of the materials themselves has been an ongoing journey throughout my life.</p>
      </article>
      <article data-reveal>
        <h3>Where did you get the inspiration from for this particular piece? (Please select one of your latest pieces that you can submit a good photograph of or have Stuart photograph)</h3>
        <p>“Earth Shrine’ has evolved. Twenty years ago my first exhibition ‘Divine Elements’ (1997) had shadow boxes which paid homage to Papatuanuku. These shrines are more relevant today as they have evolved over time and enable the viewer to become participant, offering a place of contemplation, mindfulness, rest and reflection.</p>
      </article>
      <article data-reveal>
        <h3>Tell me a little bit about your relationship with art and being creative?</h3>
        <p>The creative process is necessary for me to be whole, balanced and uplifted. Nature and its earth based ways of being is intuitive and tells my story. I have been an art teacher, facilitator, performer, and maker. This is my first year of opening my studio to the public and I am excited at the opportunity to share my beautiful creative space “Waimaunga “here on Karioi’.</p>
      </article>
      <article data-reveal>
        <h3>Which artists do you admire, past and present? Why? What draws you to their work?</h3>
        <p>A huge range from early religious iconography renaissance painters to contemporary feminist and environmental activists. Surrealist narrative painters. Indigenous artists. More recently studying ceramic and clay sculpture artists. There are way too many to list</p>
      </article>
      <article data-reveal>
        <h3>What are you working on at the moment?</h3>
        <p>The Elemental Shrines: Earth, Air, Fire and Water which will be available to view during the Arts Trail weekend. Early ancient female archetypes in clay.</p>
      </article>
      <article data-reveal>
        <h3>Tell me something you like about living in Raglan. How is it special?</h3>
